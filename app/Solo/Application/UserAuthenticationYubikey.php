namespace Solo\Application;

use Akeeba\Engine\Platform;
use Awf\Application\Application;
use Awf\Container\ContainerAwareInterface;
use Awf\Container\ContainerAwareTrait;
use Awf\Download\Download;
use Awf\Uri\Uri;
use Solo\Helper\HashHelper;

class UserAuthenticationYubikey extends UserAuthenticationOtep implements ContainerAwareInterface
{
	use ContainerAwareTrait;

	/**
	 * Is this user authenticated by this object? The $params array contains at least one key, 'password'.
	 *
	 * @param   array   $params    The parameters used in the authentication process
	 *
	 * @return  boolean  True if the user is authenticated (or this plugin doesn't apply), false otherwise
	 */
	public function onAuthentication($params = array())
	{
		$result = true;

		$userParams = $this->user->getParameters();

		if ($userParams->get('tfa.method', 'none') == 'yubikey')
		{
			$result = false;

			$secret = isset($params['secret']) ? $params['secret'] : '';

			if (!empty($secret))
			{
				// Only ask YubiCloud about OTPs generated by the YubiKey this user has enrolled.
				$result = $this->isEnrolledYubikey($secret) && $this->validateYubikeyOTP($secret);

				if (!$result)
				{
					$result = $this->validateOtep($secret);
				}
			}
		}

		return $result;
	}

	public function onTfaSave($tfaParams)
	{
		$tfaMethod = isset($tfaParams['method']) ? $tfaParams['method'] : '';

		if ($tfaMethod == 'yubikey')
		{
			// The YubiKey code set by the user in the form: an OTP, or the stored public ID posted back unchanged
			$newCode = isset($tfaParams['yubikey']) ? $tfaParams['yubikey'] : '';
			$newCode = is_string($newCode) ? trim($newCode) : '';
			// The public ID of the YubiKey in the user object
			$oldId = $this->getStoredYubikeyId();
			// What was the old TFA method?
			$oldTfaMethod = $this->user->getParameters()->get('tfa.method');

			// The public ID of the YubiKey the user is submitting
			$newId = $this->getYubikeyPublicId($newCode);

			if (($oldTfaMethod == 'yubikey') && ($oldId !== '') && hash_equals($oldId, $newId !== '' ? $newId : $newCode))
			{
				// We had already set up YubiKey and it is the same key. No change performed here.
				return true;
			}
			else
			{
				// Safe fallback until we can verify the new yubikey
				$this->user->getParameters()->set('tfa', null);
				$this->user->getParameters()->set('tfa.method', 'none');

				if (($newId !== '') && $this->validateYubikeyOTP($newCode))
				{
					$this->user->getParameters()->set('tfa.method', 'yubikey');
					// Store only the public ID of the YubiKey, never the one-time password itself
					$this->user->getParameters()->set('tfa.yubikey', $newId);
				}
			}
		}

		return true;
	}

	/**
	 * Returns the public ID of the YubiKey which generated the given OTP.
	 *
	 * A YubiKey OTP is 32 modhex characters of encrypted payload, preceded by the 2-16 character public ID of the key.
	 *
	 * @param   mixed  $otp  The OTP generated by the YubiKey
	 *
	 * @return  string  The public ID; empty string if $otp does not look like a YubiKey OTP.
	 */
	protected function getYubikeyPublicId($otp): string
	{
		if (!is_string($otp) || !preg_match('/^[cbdefghijklnrtuv]{34,48}$/', $otp))
		{
			return '';
		}

		return substr($otp, 0, -32);
	}

	/**
	 * Returns the public ID of the YubiKey enrolled by the user.
	 *
	 * Older versions stored the entire OTP used during enrolment; in that case the public ID is derived from it.
	 *
	 * @return  string  The public ID; empty string if no YubiKey is enrolled.
	 */
	protected function getStoredYubikeyId(): string
	{
		$stored = $this->user->getParameters()->get('tfa.yubikey', '');

		if (!is_string($stored) || $stored === '')
		{
			return '';
		}

		if (strlen($stored) > 32)
		{
			return $this->getYubikeyPublicId($stored);
		}

		return $stored;
	}

	/**
	 * Does the OTP come from the YubiKey the user has enrolled?
	 *
	 * @param   mixed  $otp  The OTP generated by the YubiKey
	 *
	 * @return  bool
	 */
	protected function isEnrolledYubikey($otp): bool
	{
		$storedId = $this->getStoredYubikeyId();
		$otpId    = $this->getYubikeyPublicId($otp);

		if ($storedId === '' || $otpId === '')
		{
			return false;
		}

		return hash_equals($storedId, $otpId);
	}

	/**
	 * Validates a Yubikey OTP against the Yubikey servers
	 *
	 * @param   string  $otp  The OTP generated by your Yubikey
	 *
	 * @return  boolean  True if it's a valid OTP
	 */
	public function validateYubikeyOTP($otp)
	{
		$server_queue = array(
			'api.yubico.com', 'api2.yubico.com', 'api3.yubico.com',
			'api4.yubico.com', 'api5.yubico.com'
		);

		shuffle($server_queue);

		$gotResponse = false;
		$check = false;

		$options = [];
		$proxyParams = Platform::getInstance()->getProxySettings();

		if ($proxyParams['enabled'])
		{
			$options['proxy'] = [
				'host' => $proxyParams['host'],
				'port' => $proxyParams['port'],
				'user' => $proxyParams['user'],
				'pass' => $proxyParams['pass'],
			];
		}

		$http = new Download($this->getContainer());
		$http->setAdapterOptions($options);

		$nonce    = function_exists('random_bytes') && function_exists('bin2hex')
			? bin2hex(random_bytes(16))
			: HashHelper::md5($this->getContainer()->session->getCsrfToken()->getValue() . uniqid(rand()));
		$response = '';

		while (!$gotResponse && !empty($server_queue))
		{
			$server = array_shift($server_queue);

			$uri = new Uri('https://' . $server . '/wsapi/2.0/verify');

			// I don't see where this ID is used?
			$uri->setVar('id', 1);

			// The OTP we read from the user
			$uri->setVar('otp', $otp);

			// This prevents a REPLAYED_OTP status of the token doesn't change
			// after a user submits an invalid OTP
			$uri->setVar('nonce', $nonce);

			// Minimum service level required: 50% (at least 50% of the YubiCloud
			// servers must reply positively for the OTP to validate)
			$uri->setVar('sl', 50);

			// Timeou waiting for YubiCloud servers to reply: 5 seconds.
			$uri->setVar('timeout', 5);

			try
			{
				$response = $http->getFromURL($uri->toString());

				if (!empty($response))
				{
					$gotResponse = true;
				}
				else
				{
					continue;
				}
			}
			catch (\Exception $exc)
			{
				// No response, continue with the next server
				continue;
			}
		}

		// No server replied; we can't validate this OTP
		if (!$gotResponse)
		{
			return false;
		}

		// Parse response
		$lines = explode("\n", $response);
		$data = array();

		foreach ($lines as $line)
		{
			$line = trim($line);

			$parts = explode('=', $line, 2);

			if (count($parts) < 2)
			{
				continue;
			}

			$data[$parts[0]] = $parts[1];
		}

		// Validate the response - We need an OK message reply
		if (($data['status'] ?? null) !== 'OK')
		{
			return false;
		}

		// Validate the response - We need a confidence level over 50%
		if (!isset($data['sl']) || !is_numeric($data['sl']) || $data['sl'] < 50)
		{
			return false;
		}

		// Validate the response - The OTP must match
		if (($data['otp'] ?? null) !== $otp)
		{
			return false;
		}

		// Validate the response - The token must match
		if (($data['nonce'] ?? null) !== $nonce)
		{
			return false;
		}

		return true;
	}
}
